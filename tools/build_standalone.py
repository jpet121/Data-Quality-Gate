"""Reproducibly assemble an independent single-file CLI from audited modules.

The source modules remain testable and separately maintained. The generated
main.py contains the full parser, models, configuration, repositories, and CLI.
Only the declared Pydantic v2 runtime dependency is required for core features.
"""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
MODULES = (
    'models', 'matrix', 'parser', 'core', 'storage', 'workflow', 'postgres', 'cli'
)


def assemble() -> str:
    parts = [
        '# Generated by tools/build_standalone.py; DO NOT EDIT DIRECTLY.\n',
        '# Self-contained implementation; requires Pydantic v2 (and optionally psycopg).\n',
        'from __future__ import annotations\n',
    ]
    for name in MODULES:
        source_path = ROOT / 'src' / 'event_validator' / f'{name}.py'
        source = source_path.read_text(encoding='utf-8')
        # Check import syntax so only explicitly anticipated in-package
        # imports disappear; imports of third-party libraries remain.
        tree = ast.parse(source, filename=str(source_path), feature_version=(3, 12))
        relative_lines = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.level:
                if node.level != 1 or node.module not in {
                    'models', 'matrix', 'parser', 'storage', 'core'
                }:
                    raise RuntimeError(f'Unsafe relative import: {source_path}:{node.lineno}')
                relative_lines.update(range(node.lineno, node.end_lineno + 1))
        lines = []
        for number, line in enumerate(source.splitlines(keepends=True), 1):
            if number in relative_lines or line.startswith('from __future__ import'):
                continue
            lines.append(line)
        segment = ''.join(lines)
        if name == 'storage':
            ddl = (ROOT / 'migrations' / '001_sqlite.sql').read_text(encoding='utf-8')
            if f'DDL_SQL = {ddl!r}' not in segment:
                raise RuntimeError('Packaged SQLite migration differs from source migration')
        parts.append(f'\n# --- BEGIN src/event_validator/{name}.py ---\n')
        parts.append(segment.rstrip() + '\n')
    parts.append('\nif __name__ == "__main__":\n    raise SystemExit(main())\n')
    result = ''.join(parts)
    ast.parse(result, filename='main.py', feature_version=(3, 12))
    if 'from .' in result or 'import event_validator' in result:
        raise RuntimeError('Standalone output references package')
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Fail if generated main.py is not current')
    args = parser.parse_args()
    result = assemble()
    dest = ROOT / 'main.py'
    if args.check:
        if not dest.exists() or dest.read_text(encoding='utf-8') != result:
            print('main.py differs from generator output', file=sys.stderr)
            return 1
        return 0
    dest.write_text(result, encoding='utf-8')
    print(f'Generated {dest.name} ({len(result.encode("utf-8"))} bytes)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
